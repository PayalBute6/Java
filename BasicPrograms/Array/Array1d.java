// Program to demonstrate 1D Array Declaration, Initialization, and Iteration in Java
public class Array1d { 
    public static void main(String args[]) { 
        // Declaration and initialization of a 1-Dimensional integer array
        int a[] = {100, 200, 300, 400, 500}; 
        
        // Traverse and print array elements using a standard for loop
        for (int i = 0; i < a.length; i++) { 
            // Print each array element at index i
            System.out.print(" " + a[i]); 
        } 
        System.out.println();
    } 
}

