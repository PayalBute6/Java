// Program to demonstrate a standard for loop in Java (prints numbers from 1 to 10)
public class ForDemo { 
    public static void main(String[] args) { 
        // Syntax of for loop: for (initialization; condition; increment/decrement)
        // 1. Initialization (int i = 1): Executed once when the loop starts
        // 2. Condition (i <= 10): Checked before every iteration. Runs as long as true
        // 3. Increment (i++): Executed after the loop body in every iteration
        for (int i = 1; i <= 10; i++) { 
            // Loop Body: Prints the current value of i
            System.out.println("Value of  i = : " + i + "  "); 
        } 
    } 
}
 