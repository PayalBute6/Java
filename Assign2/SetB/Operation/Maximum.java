/*
 * Set B - e
 * Maximum has a method max () to display the maximum of two Integers 
 */

public class Maximum {
    public void max(int a, int b) {
        if (a > b) {
            System.out.println("Maximum is: " + a);
        } else {
            System.out.println("Maximum is: " + b);
        }
    }
}
